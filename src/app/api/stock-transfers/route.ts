import { NextResponse } from 'next/server';
import { requirePermission } from '@/lib/server/rbac';
import { logAudit } from '@/lib/server/audit';
import { listStockTransfers, createStockTransfer } from '@/lib/server/procurement';

export async function GET(request: Request) {
  const { error } = requirePermission(request, 'procurement:read');
  if (error) return NextResponse.json({ error }, { status: error === 'Unauthorized' ? 401 : 403 });
  const url = new URL(request.url);
  const transfers = listStockTransfers({
    status: url.searchParams.get('status') || undefined,
    productReference: url.searchParams.get('productReference') || undefined,
    limit: url.searchParams.get('limit') ? Number(url.searchParams.get('limit')) : undefined,
    page: url.searchParams.get('page') ? Number(url.searchParams.get('page')) : undefined,
  });
  return NextResponse.json({ transfers });
}

export async function POST(request: Request) {
  const { error } = requirePermission(request, 'procurement:write');
  if (error) return NextResponse.json({ error }, { status: error === 'Unauthorized' ? 401 : 403 });
  try {
    const body = await request.json();
    const transfer = createStockTransfer(body);
    try { await logAudit('stock_transfer', transfer.reference, 'created', `Stock transfer ${transfer.reference}: ${transfer.quantity} ${transfer.productReference}`); } catch (e) { console.error(e); }
    return NextResponse.json({ transfer }, { status: 201 });
  } catch (err) {
    return NextResponse.json({ error: err instanceof Error ? err.message : 'Unknown error' }, { status: 400 });
  }
}
